package exercicios;

public class QuizPOO {

    //Quiz Javanauta - Programação Orientada a Objetos

    //1) O que é um objeto em Programação Orientada a Objetos?

    //Resposta: Uma instância de uma classe que pode conter atributos e métodos.

    /*---------------------------------------*/

    //2) Qual dos seguintes é um pilar da Programação Orientada a Objetos?

    //Resposta: Polimorfismo.

    /*---------------------------------------*/

    //3) O que é encapsulamento em POO?

    //Resposta: A técnica de esconder os detalhes internos de um objeto e expor apenas os métodos necessários.

    /*---------------------------------------*/

    //4) Como se chama o processo de criar uma nova classe a partir de uma classe existente?

    //Resposta: Herança.

    /*---------------------------------------*/

    //5) Qual é a finalidade do polimorfismo em POO?

    //Resposta: Permitir que métodos diferentes sejam chamados com o mesmo nome.

    /*---------------------------------------*/

    //6) Qual é a principal diferença entre um método estático e um métodode instância em Java?

    //Resposta: Um método estático pertence à classe e pode ser chamado sem criar uma instância da classe,
    //          enquanto um método de instância pertence a um objeto e requer uma instância da classe para ser chamada.

    /*---------------------------------------*/
}
